package com.pulse.messenger;

import android.app.Application;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.os.Build;

import com.google.firebase.firestore.FirebaseFirestore;
import com.google.firebase.firestore.FirebaseFirestoreSettings;
import com.google.firebase.firestore.PersistentCacheSettings;

/**
 * Application entry point.
 *
 * <p>Responsibilities:</p>
 * <ol>
 *   <li>Configure Firestore to use persistent disk cache so messages,
 *       conversations, and profiles survive process death and remain
 *       readable while offline. This MUST run before the first
 *       Firestore operation, otherwise the SDK has already frozen its
 *       settings and throws {@code IllegalStateException}.</li>
 *   <li>Register notification channels used by {@code FcmService}.
 *       Channels must exist before the first notification is posted on
 *       Android O (API 26); otherwise Android drops the notification
 *       silently with no error.</li>
 * </ol>
 *
 * <p>FirebaseApp initialization is performed automatically by the
 * ContentProvider generated by the Google Services Gradle plugin. This
 * class deliberately does not call {@code FirebaseApp.initializeApp()}
 * a second time.</p>
 *
 * <p>Presence tracking (Realtime Database online/offline mirror) is
 * registered later — see {@code data.PresenceManager} — because it
 * requires a signed-in user and the classes that manage activity
 * lifecycle callbacks.</p>
 */
public class App extends Application {

    @Override
    public void onCreate() {
        super.onCreate();

        configureFirestore();
        createNotificationChannels();
    }

    /**
     * Enables Firestore's persistent disk cache.
     *
     * <p>Persistent cache means that when the app is offline (or the
     * user briefly loses connectivity), reads are served from local
     * disk and pending writes are queued until connectivity returns.
     * Without this, every cold start re-reads the entire chat list
     * and every message page from the network — which is unacceptable
     * on a messaging app running on a low-end phone over a slow
     * mobile connection.</p>
     *
     * <p>The default cache size (100 MB) is used. Cache size is a
     * ceiling, not a preallocation; the app typically consumes far
     * less.</p>
     */
    private void configureFirestore() {
        FirebaseFirestoreSettings settings = new FirebaseFirestoreSettings.Builder()
                .setLocalCacheSettings(PersistentCacheSettings.newBuilder().build())
                .build();
        FirebaseFirestore.getInstance().setFirestoreSettings(settings);
    }

    /**
     * Creates the two notification channels used by the app:
     * one for direct messages and one for group messages. Both are
     * {@code IMPORTANCE_HIGH} so a message wakes the screen when the
     * user has not muted the conversation.
     *
     * <p>The channel IDs are stable string resources in
     * {@code res/values/strings.xml} because the same IDs must be
     * referenced from three places: here, from
     * {@code FcmService} when posting, and from the manifest's
     * {@code default_notification_channel_id} meta-data.</p>
     *
     * <p>Channels are created on every cold start. This is safe — the
     * system ignores {@code createNotificationChannel} for a channel
     * that already exists (user-customized settings are preserved).</p>
     */
    private void createNotificationChannels() {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) {
            return;
        }

        NotificationManager nm = getSystemService(NotificationManager.class);
        if (nm == null) {
            return;
        }

        NotificationChannel messages = new NotificationChannel(
                getString(R.string.channel_id_messages),
                getString(R.string.channel_messages_name),
                NotificationManager.IMPORTANCE_HIGH);
        messages.setDescription(getString(R.string.channel_messages_desc));
        messages.enableVibration(true);
        messages.setShowBadge(true);
        nm.createNotificationChannel(messages);

        NotificationChannel groups = new NotificationChannel(
                getString(R.string.channel_id_groups),
                getString(R.string.channel_groups_name),
                NotificationManager.IMPORTANCE_HIGH);
        groups.setDescription(getString(R.string.channel_groups_desc));
        groups.enableVibration(true);
        groups.setShowBadge(true);
        nm.createNotificationChannel(groups);
    }
}
